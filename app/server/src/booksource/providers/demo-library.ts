export class DemoLibraryProvider implements BookSource {
  id = 'demo';
  name = '内置示例库';
  type = 'open' as const;
  enabled = true;

  async search(query: string): Promise<BookSearchResult[]> {
    const q = query.toLowerCase().trim();
    const matched = DEMO_BOOKS.filter(
      (b) =>
        b.title.toLowerCase().includes(q) ||
        q.includes(b.title.toLowerCase()) ||
        b.author.toLowerCase().includes(q) ||
        b.keywords.some((k) => k.includes(q) || q.includes(k)),
    );

    // 在线源不可用且无精确匹配时，返回全部示例书目作为可选候选
    const books = matched.length > 0 ? matched : DEMO_BOOKS;

    return books.map((b) => ({
      id: `demo-${b.id}`,
      title: b.title,
      author: b.author,
      source: '内置示例库',
      provider: 'demo',
      intro: b.intro,
      formats: ['txt'],
    }));
  }

  async download(result: BookSearchResult): Promise<string> {
    const book = DEMO_BOOKS.find((b) => `demo-${b.id}` === result.id);
    if (!book) throw new Error('示例书目不存在');
    return book.content;
  }
}
